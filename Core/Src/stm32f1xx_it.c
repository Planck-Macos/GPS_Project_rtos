void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
	BaseType_t xHighPriorityTaskWoken = pdFALSE;
	if(huart->Instance == USART2)
	{
		if(uart2_rx_byte == '\n')//判断是否接收完毕
		{
			if(uart2_line_pos > 0)//判断是否有数据，是否不是空行
			{
				note_t note;
        //memcpy：将uart2_line_buf中的数据复制到note.data中，包括终止符，len为uart2_line_pos+1
				memcpy(note.data,uart2_line_buf,uart2_line_pos);    //把接收到的数据复制到note.data中
				note.data[uart2_line_pos] = '\0';                   //添加终止符，也就是将数据处理为字符串
				note.len = uart2_line_pos;                          //记录该行的有效数据长度
				write_data_to_loop_buffer(&bd_uart_loop_buffer,&note);//将note写入循环缓冲区
				xTaskNotifyFromISR(gpstaskHandle,0,eIncrement,&xHighPriorityTaskWoken);
				portYIELD_FROM_ISR(xHighPriorityTaskWoken);//中断上下文任务切换宏 若参数中为pdTRUE，则退出该任务，触发任务切换
			}
			uart2_line_pos = 0;
		}
		else
		{
			if(uart2_line_pos < MAX_SIZE - 1)
			{
				uart2_line_buf[uart2_line_pos++] = uart2_rx_byte;
			}
			else
			{
				uart2_line_pos = 0;
			}
		}
		HAL_UART_Receive_IT(&huart2,&uart2_rx_byte,1);
	}
}

